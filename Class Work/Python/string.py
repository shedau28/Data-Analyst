s = "Python Programming"

print(len(s))

print(s.capitalize()) #Capatilize first latter only
print(s.upper()) #string in upper case
print(s.lower()) #string in lower case
print(s.casefold()) #string in lower case
print(s.count("P")) #Find every P and return count
print(s.find("t")) #Find Index of t
print(s.index("P",2)) #Find index of P which comes after 2nd index
print(s.replace("P", "C")) #Replace P with C
print(s.isalpha()) #Return True or False, Space not counts in alpha or numeric
print(s.title()) #Convert case of first char of every word into upper case
print(s.swapcase()) #swap case of chars.




